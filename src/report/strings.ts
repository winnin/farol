export const MARKER = '<!-- farol -->'

const plural = (n: number, one: string, many: string): string => `${n} ${n === 1 ? one : many}`

/** The entry-point unit of a report: pages for a frontend, operations (GraphQL fields, REST endpoints) for a backend. */
export interface Terms {
  /** With its article: "a page", "an operation". */
  aOne: string
  one: string
  many: string
  Many: string
  section: string
}

const FRONTEND_TERMS: Terms = { aOne: 'a page', one: 'page', many: 'pages', Many: 'Pages', section: 'Routes' }
const BACKEND_TERMS: Terms = { aOne: 'an operation', one: 'operation', many: 'operations', Many: 'Operations', section: 'Operations' }

export function terms(surface: 'frontend' | 'backend'): Terms {
  return surface === 'backend' ? BACKEND_TERMS : FRONTEND_TERMS
}

